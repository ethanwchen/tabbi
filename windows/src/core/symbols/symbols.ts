/** An SF Symbol name the table knows. */
export type SymbolName = keyof typeof SYMBOL_ICONS;

/** The neutral icon drawn for a name the table does not know. */
export const FALLBACK_ICON = "placeholder";

/** A neutral icon id the UI draws. */
export type IconId = (typeof SYMBOL_ICONS)[SymbolName] | typeof FALLBACK_ICON;

/**
 * The icon for an SF Symbol name, from a kit, a descriptor or the core. An
 * unknown name (a newer kit, a typo) draws the neutral placeholder instead of
 * nothing, the way the Mac draws `square.dashed` for an unknown module.
 */
export function iconId(symbolName: string): IconId {
  return Object.hasOwn(SYMBOL_ICONS, symbolName) ? SYMBOL_ICONS[symbolName as SymbolName] : FALLBACK_ICON;
}
