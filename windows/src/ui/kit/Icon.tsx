/* Icons that point along the reading direction, mirrored under rtl. */
const MIRRORED = new Set<IconId>(["chevron-backward", "chevron-forward", "reply", "undo", "redo", "go-filled", "open-app", "open-app-filled", "collapse", "expand", "schedule", "checklist", "playlist", "terminal", "code"]);

export interface IconProps {
  /** An icon id from core/symbols, or an SF Symbol name which is looked up there. */
  readonly id: string;
  /** The square size in CSS pixels. */
  readonly size?: number;
  readonly className?: string;
  readonly style?: CSSProperties;
  /** Keeps the icon as drawn in a right-to-left language (a check mark, a media control). */
  readonly fixedDirection?: boolean;
}

/** The icon id `name` draws, whether `name` is an id or an SF Symbol name. */
export function resolveIconId(name: string): IconId {
  if (Object.hasOwn(GLYPHS, name)) return name as IconId;
  return iconId(name);
}

/** Every icon id the kit draws, in table order. */
export const ICON_IDS: readonly IconId[] = Object.keys(GLYPHS) as IconId[];

export function Icon({ id, size = 16, className, style, fixedDirection = false }: IconProps) {
  const resolved = resolveIconId(id);
  const classes = ["kit-icon", className].filter(Boolean).join(" ");
  return (
    <svg
      className={classes}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      aria-hidden="true"
      focusable="false"
      data-icon={resolved}
      data-mirror={MIRRORED.has(resolved) && !fixedDirection ? "" : undefined}
      style={style}
    >
      {GLYPHS[resolved]}
    </svg>
  );
}


