#!/usr/bin/env bash
# Compiles Tabbi's String Catalog into the per-language .lproj folders the
# app ships, one Localizable.strings and one Localizable.stringsdict (the
# plurals) per language.
#
#   usage: scripts/compile-strings.sh
#
# Localizable.xcstrings is the one file people edit (docs/localization.md).
# The compiled folders in Sources/TabbiKitCore/Localization/Strings are
# committed, and Package.swift copies that folder as is into TabbiKitCore's
# resource bundle instead of handing SwiftPM the catalog. Whether SwiftPM
# compiles a catalog depends on its version (Swift 6.3 copies it untouched,
# so every string stays English), and its older build system lowercases the
# .lproj names it processes (pt-br, zh-hans); a copied folder ships the same
# on every toolchain. Run this after every catalog change: LocalizationTests
# fails until the compiled files match the catalog.
set -euo pipefail
cd "$(dirname "$0")/.."

localization=Sources/TabbiKitCore/Localization
catalog=$localization/Localizable.xcstrings
compiled=$localization/Strings

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

xcrun xcstringstool compile "$catalog" --output-directory "$work" \
    --format stringsAndStringsdict --serialization-format text

# Both files are XML property lists, which allow a comment after the
# doctype; it tells readers where the file comes from.
header="<!-- Generated by scripts/compile-strings.sh from Localizable.xcstrings. Do not edit by hand: edit the catalog and run the script again. -->"
for file in "$work"/*.lproj/*; do
    awk -v header="$header" '{ print } /^<!DOCTYPE plist/ && !done { print header; done = 1 }' "$file" > "$file.tmp"
    plutil -lint -s "$file.tmp"
    mv "$file.tmp" "$file"
done

# Replace the whole folder, so a language or file the catalog no longer
# produces does not linger.
rm -rf "$compiled"
mkdir -p "$compiled"
cp -R "$work"/*.lproj "$compiled/"
echo "Compiled $catalog into $(find "$compiled" -name '*.lproj' | wc -l | tr -d ' ') languages in $compiled"
